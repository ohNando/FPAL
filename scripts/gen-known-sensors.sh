#!/bin/sh
# SPDX-License-Identifier: Apache-2.0
#
# Print tools/known_sensors.h: every USB id that libfprint knows, with the
# libfprint driver that handles it and whether that driver is a
# Match-on-Chip one. Used by "fpal report" to tell a new sensor's owner what
# the chip is and how far away it is from support.
#
#   scripts/gen-known-sensors.sh /path/to/libfprint/libfprint/drivers [VERSION]
#       > tools/known_sensors.h
#
# The vendor and product ids are read from the "{ .vid = ..., .pid = ... }"
# tables of the driver sources; names such as ELAN_VEND_ID are resolved from
# the #define lines. SPI sensors (elanspi) are not USB and are left out.
set -eu

dir=${1:?usage: gen-known-sensors.sh DRIVERS_DIR [LIBFPRINT_VERSION]}
version=${2:-unknown}
[ -d "$dir" ] || { echo "gen-known-sensors: $dir is not a directory" >&2; exit 1; }

cat <<HDR
/* SPDX-License-Identifier: Apache-2.0 */
/*
 * GENERATED by scripts/gen-known-sensors.sh from libfprint $version. Do not
 * edit by hand. Sorted by vendor id, then product id.
 */
#ifndef FPAL_TOOLS_KNOWN_SENSORS_H
#define FPAL_TOOLS_KNOWN_SENSORS_H

#include <stdbool.h>
#include <stdint.h>

struct fpal_known_sensor {
	uint16_t vid, pid;
	const char *libfprint; /* libfprint driver that handles it */
	bool moc;	       /* Match-on-Chip (the templates live on the chip) */
};

#define FPAL_KNOWN_SENSORS_SOURCE "libfprint $version"

static const struct fpal_known_sensor fpal_known_sensors[] = {
HDR

# One record per id: "vid pid driver moc". Macro values first, then the ids.
find "$dir" \( -name '*.c' -o -name '*.h' \) | LC_ALL=C sort | while read -r f; do
	rel=${f#"$dir"/}
	case $rel in
	*/*) drv=${rel%%/*} ;;
	*) drv=${rel%.*} ;;
	esac
	printf '%s\t%s\n' "$drv" "$f"
done | awk -F'\t' '
function hex(s) {
	s = tolower(substr(s, 3))
	while (length(s) < 4)
		s = "0" s
	return s
}
{
	drv = $1; file = $2
	# Pass 1 over this file: remember "#define NAME 0x...." values.
	while ((getline line < file) > 0)
		if (match(line, /^[ \t]*#[ \t]*define[ \t]+[A-Za-z_0-9]+[ \t]+0x[0-9a-fA-F]+/)) {
			n = split(substr(line, RSTART, RLENGTH), p, /[ \t]+/)
			def[p[n - 1]] = p[n]
		}
	close(file)
	# Pass 2: the id entries.
	while ((getline line < file) > 0) {
		if (line !~ /\.vid[ \t]*=/ || line !~ /\.pid[ \t]*=/)
			continue
		v = line; sub(/.*\.vid[ \t]*=[ \t]*/, "", v); sub(/[^A-Za-z_0-9].*/, "", v)
		q = line; sub(/.*\.pid[ \t]*=[ \t]*/, "", q); sub(/[^A-Za-z_0-9].*/, "", q)
		if (v ~ /^[A-Za-z_]/) v = (v in def) ? def[v] : ""
		if (q ~ /^[A-Za-z_]/) q = (q in def) ? def[q] : ""
		if (v !~ /^0x/ || q !~ /^0x/ || v == "0x0" || v == "0")
			continue
		if (drv == "elanspi")
			continue # SPI, not USB
		print hex(v), hex(q), drv
	}
	close(file)
}' | LC_ALL=C sort -u | awk '
{
	moc = ($3 ~ /moc$/ || $3 == "synaptics" || $3 == "realtek") ? "true" : "false"
	printf "\t{ 0x%s, 0x%s, \"%s\", %s },\n", $1, $2, $3, moc
}'

cat <<'FTR'
};

#endif /* FPAL_TOOLS_KNOWN_SENSORS_H */
FTR
